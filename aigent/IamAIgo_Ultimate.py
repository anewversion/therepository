class MemoryManager:
    def __init__(self):
        self.conn = sqlite3.connect(str(config.memory_db), check_same_thread=False)
        self.create_tables()
        self.current_session_id = str(int(time.time()))

    def create_tables(self):
        cursor = self.conn.cursor()
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS conversations (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                session_id TEXT,
                role TEXT,
                content TEXT,
                timestamp DATETIME DEFAULT CURRENT_TIMESTAMP
            )
        """)
        # Try to enable FTS5
        try:
            cursor.execute("CREATE VIRTUAL TABLE IF NOT EXISTS knowledge_base USING fts5(topic, content, source)")
        except Exception:
            logger.warning("FTS5 not supported, falling back to standard table.")
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS knowledge_base (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    topic TEXT,
                    content TEXT,
                    source TEXT,
                    timestamp DATETIME DEFAULT CURRENT_TIMESTAMP
                )
            """)
        self.conn.commit()

    def add_message(self, role: str, content: str):
        cursor = self.conn.cursor()
        cursor.execute(
            "INSERT INTO conversations (session_id, role, content) VALUES (?, ?, ?)",
            (self.current_session_id, role, content)
        )
        self.conn.commit()

    def get_history(self, limit: int = 20) -> List[Dict[str, str]]:
        cursor = self.conn.cursor()
        cursor.execute(
            "SELECT role, content FROM conversations WHERE session_id = ? ORDER BY id DESC LIMIT ?",
            (self.current_session_id, limit)
        )
        rows = cursor.fetchall()
        return [{"role": r[0], "content": r[1]} for r in reversed(rows)]

    def search_knowledge(self, query: str) -> str:
        cursor = self.conn.cursor()
        try:
            # Try FTS search
            cursor.execute(
                "SELECT content FROM knowledge_base WHERE knowledge_base MATCH ? LIMIT 3",
                (query,)
            )
        except Exception:
            # Fallback to LIKE
            cursor.execute(
                "SELECT content FROM knowledge_base WHERE content LIKE ? LIMIT 3",
                (f"%{query}%",)
            )
            
        rows = cursor.fetchall()
        if not rows:
            return ""
        return "\n\nRelevant Knowledge:\n" + "\n".join([r[0] for r in rows])

