class Tools:
    @staticmethod
    def _is_safe_path(path_str: str) -> bool:
        try:
            path = Path(path_str).resolve()
            for root in config.allowed_roots:
                if str(path).startswith(str(root.resolve())):
                    return True
            return False
        except Exception:
            return False

    @staticmethod
    def read_file(file_path: str) -> str:
        """Reads the content of a file."""
        try:
            if not Tools._is_safe_path(file_path):
                return f"Error: Access to {file_path} is not allowed."
                
            path = Path(file_path)
            if not path.exists():
                return f"Error: File {file_path} does not exist."
            
            # Basic binary check
            try:
                with open(path, 'r', encoding='utf-8') as f:
                    return f.read()
            except UnicodeDecodeError:
                return f"Error: File {file_path} appears to be binary and cannot be read as text."
        except Exception as e:
            return f"Error reading file: {str(e)}"

    @staticmethod
    def write_file(file_path: str, content: str) -> str:
        """Writes content to a file. Creates directories if needed."""
        try:
            if not Tools._is_safe_path(file_path):
                return f"Error: Access to {file_path} is not allowed."

            path = Path(file_path)
            path.parent.mkdir(parents=True, exist_ok=True)
            
            # Backup if exists
            if path.exists():
                backup_path = path.with_suffix(path.suffix + ".bak")
                shutil.copy2(path, backup_path)
            
            with open(path, 'w', encoding='utf-8') as f:
                f.write(content)
            return f"Successfully wrote to {file_path}"
        except Exception as e:
            return f"Error writing file: {str(e)}"

    @staticmethod
    def list_directory(dir_path: str) -> str:
        """Lists files in a directory."""
        try:
            if not Tools._is_safe_path(dir_path):
                return f"Error: Access to {dir_path} is not allowed."

            path = Path(dir_path)
            if not path.exists():
                return f"Error: Directory {dir_path} does not exist."
            
            items = []
            for item in path.iterdir():
                type_str = "DIR" if item.is_dir() else "FILE"
                items.append(f"[{type_str}] {item.name}")
            return "\n".join(items)
        except Exception as e:
            return f"Error listing directory: {str(e)}"

    @staticmethod
    def web_search(query: str) -> str:
        """Searches the web using DuckDuckGo."""
        if not DDGS_AVAILABLE:
            return "Error: ddgs library not installed. Cannot perform web search."
        
        try:
            # DDGS usage
            results = []
            with DDGS() as ddgs:
                # text() returns an iterator
                ddgs_gen = ddgs.text(query, max_results=5)
                if ddgs_gen:
                    results = list(ddgs_gen)
            
            if not results:
                return "No results found."
            
            formatted = []
            for r in results:
                title = r.get('title', 'No Title')
                href = r.get('href', 'No Link')
                body = r.get('body', 'No Content')
                formatted.append(f"Title: {title}\nLink: {href}\nSnippet: {body}\n")
            return "\n".join(formatted)
        except Exception as e:
            return f"Error performing web search: {str(e)}"

    @staticmethod
    def send_email(to_email: str, subject: str, body: str, attachments: List[str] = None) -> str:
        """Sends an email using configured SMTP server with optional attachments."""
        if not config.email_user or not config.email_password:
            return "Error: Email credentials not configured in environment variables."
        
        try:
            msg = MIMEMultipart()
            msg['From'] = config.email_user
            msg['To'] = to_email
            msg['Subject'] = subject
            msg.attach(MIMEText(body, 'plain'))
            
            if attachments:
                for file_path in attachments:
                    path = Path(file_path)
                    if not path.exists():
                        return f"Error: Attachment {file_path} does not exist."
                    
                    try:
                        with open(path, "rb") as attachment:
                            part = MIMEBase("application", "octet-stream")
                            part.set_payload(attachment.read())
                        
                        encoders.encode_base64(part)
                        part.add_header(
                            "Content-Disposition",
                            f"attachment; filename= {path.name}",
                        )
                        msg.attach(part)
                    except Exception as e:
                        return f"Error attaching file {file_path}: {str(e)}"
            
            with smtplib.SMTP(config.smtp_server, config.smtp_port) as server:
                server.starttls()
                server.login(config.email_user, config.email_password)
                server.send_message(msg)
            return f"Email sent successfully to {to_email}"
        except Exception as e:
            return f"Error sending email: {str(e)}"

    # execute_python removed in favor of Native Code Interpreter for OpenAI
    # Kept as a static method if needed for local fallback, but not exposed to OpenAI
    @staticmethod
    def execute_python_local(code: str) -> str:
        """Executes Python code locally (Sandbox-ish)."""
        try:
            with open("temp_exec.py", "w", encoding="utf-8") as f:
                f.write(code)
            result = subprocess.run(
                [sys.executable, "temp_exec.py"],
                capture_output=True,
                text=True,
                timeout=30
            )
            output = f"Stdout:\n{result.stdout}\n\nStderr:\n{result.stderr}"
            os.remove("temp_exec.py")
            return output
        except Exception as e:
            return f"Error executing code: {str(e)}"

