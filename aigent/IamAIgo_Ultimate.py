class TrifectaCore:
    def __init__(self):
        self.openai_client = OpenAI(api_key=config.openai_api_key) if config.openai_api_key and OPENAI_AVAILABLE else None
        self.ollama_available = OLLAMA_AVAILABLE
        self.assistant = None
        self.thread = None
        
        if self.openai_client:
            self._init_assistant()

        if not self.openai_client and not self.ollama_available:
            logger.warning("No AI backends available! Please set OPENAI_API_KEY or install Ollama.")

    def _init_assistant(self):
        """Initializes or loads the OpenAI Assistant."""
        assistant_id_file = config.data_dir / "assistant_id.txt"
        
        # Check if we have a stored ID
        if assistant_id_file.exists():
            aid = assistant_id_file.read_text().strip()
            try:
                self.assistant = self.openai_client.beta.assistants.retrieve(aid)
                # Update instructions/tools in case code changed
                self.assistant = self.openai_client.beta.assistants.update(
                    aid,
                    name=config.app_name,
                    instructions=config.system_prompt,
                    tools=TOOL_DEFINITIONS,
                    model=config.openai_model
                )
                logger.info(f"Loaded Assistant: {self.assistant.id}")
                return
            except Exception as e:
                logger.warning(f"Could not retrieve assistant {aid}: {e}. Creating new one.")

        # Create new
        try:
            self.assistant = self.openai_client.beta.assistants.create(
                name=config.app_name,
                instructions=config.system_prompt,
                tools=TOOL_DEFINITIONS,
                model=config.openai_model
            )
            assistant_id_file.write_text(self.assistant.id)
            logger.info(f"Created new Assistant: {self.assistant.id}")
        except Exception as e:
            logger.error(f"Failed to create assistant: {e}")

    def _get_or_create_thread(self):
        if not self.thread:
            self.thread = self.openai_client.beta.threads.create()
        return self.thread

    def chat(self, user_input: str, history: List[Dict[str, str]], callback: Callable[[str], None] = None) -> str:
        """
        Main chat function. Uses OpenAI Assistants API (Native Agents) or falls back to Ollama.
        """
        # 1. Try OpenAI Assistants
        if self.openai_client and self.assistant:
            try:
                return self._chat_openai_assistant(user_input, callback)
            except Exception as e:
                logger.error(f"OpenAI Assistant failed: {e}. Falling back to Ollama...")
                if callback: callback(f"\n[System: OpenAI Assistant failed ({e}). Switching to Local Brain...]\n")
        
        # 2. Try Ollama
        if self.ollama_available:
            try:
                return self._chat_ollama(user_input, history, callback)
            except Exception as e:
                logger.error(f"Ollama failed: {e}")
                return f"Error: Both OpenAI and Local AI failed. {e}"
        
        return "Error: No AI backends configured or available."

    def _chat_openai_assistant(self, user_input: str, callback: Callable[[str], None]) -> str:
        thread = self._get_or_create_thread()
        
        # Add user message
        self.openai_client.beta.threads.messages.create(
            thread_id=thread.id,
            role="user",
            content=user_input
        )

        # Run the assistant (Streaming)
        # We use a loop to handle tool outputs
        
        full_response = ""
        
        # We need a custom event handler that can capture the full response for our return value
        # and also handle tool calls.
        
        class MyEventHandler(AssistantEventHandler):
            def __init__(self, client, thread_id, assistant_id):
                super().__init__()
                self.client = client
                self.thread_id = thread_id
                self.assistant_id = assistant_id
                self.full_text = ""
                
            @override
            def on_text_created(self, text) -> None:
                pass # We wait for deltas

            @override
            def on_text_delta(self, delta, snapshot):
                if delta.value:
                    self.full_text += delta.value
                    if callback: callback(delta.value)

            @override
            def on_tool_call_created(self, tool_call):
                if callback: callback(f"\n[System: Tool Call Detected: {tool_call.type}]\n")

            @override
            def on_event(self, event):
                # If we need to handle requires_action, the stream context manager exits 
                # and we get the run object? No, stream() yields events.
                # The SDK's `stream` helper is a bit complex for tool loops inside the handler.
                # It's often easier to stream, check run status, submit outputs, stream again.
                pass

        # Start the run and stream
        with self.openai_client.beta.threads.runs.stream(
            thread_id=thread.id,
            assistant_id=self.assistant.id,
            event_handler=MyEventHandler(self.openai_client, thread.id, self.assistant.id),
        ) as stream:
            stream.until_done()
            final_run = stream.get_final_run()
            
            # Capture the text generated so far
            # The event handler instance is not easily accessible here unless we kept a ref
            # But we can't easily get the text from the stream object itself after it's done?
            # Actually, we can just rely on the callback for the UI, but we need to return the string.
            # Let's assume the callback handled the UI. We need to reconstruct the full response.
            # We can't easily get it from the stream object. 
            # Let's just fetch the last message if we need it, or rely on the fact that we streamed it.
            pass

        # Handle Tool Calls if status is requires_action
        if final_run.status == "requires_action":
            tool_outputs = []
            tool_calls = final_run.required_action.submit_tool_outputs.tool_calls
            
            for tool_call in tool_calls:
                func_name = tool_call.function.name
                args_str = tool_call.function.arguments
                call_id = tool_call.id
                
                if callback: callback(f"\n[System: Executing {func_name} with {args_str}...]\n")
                
                try:
                    args = json.loads(args_str)
                    result = "Error: Unknown tool"
                    
                    if func_name == "read_file": result = Tools.read_file(args.get("file_path"))
                    elif func_name == "write_file": result = Tools.write_file(args.get("file_path"), args.get("content"))
                    elif func_name == "list_directory": result = Tools.list_directory(args.get("dir_path"))
                    elif func_name == "web_search": result = Tools.web_search(args.get("query"))
                    elif func_name == "send_email": result = Tools.send_email(args.get("to_email"), args.get("subject"), args.get("body"), args.get("attachments"))
                    elif func_name == "execute_python": result = Tools.execute_python(args.get("code"))
                    
                    tool_outputs.append({
                        "tool_call_id": call_id,
                        "output": str(result)
                    })
                    if callback: callback(f"\n[System: Tool Output: {str(result)[:100]}...]\n")
                    
                except Exception as e:
                    tool_outputs.append({
                        "tool_call_id": call_id,
                        "output": f"Error parsing arguments: {e}"
                    })

            # Submit outputs and stream again
            with self.openai_client.beta.threads.runs.submit_tool_outputs_stream(
                thread_id=thread.id,
                run_id=final_run.id,
                tool_outputs=tool_outputs,
                event_handler=MyEventHandler(self.openai_client, thread.id, self.assistant.id),
            ) as stream:
                stream.until_done()
                # We could recurse here if there are chained tool calls, but for now one level is okay
                # or we loop. Ideally we loop.
                final_run = stream.get_final_run()
                
                # Simple loop for chained calls
                while final_run.status == "requires_action":
                    # Repeat logic (refactor into a helper if needed, but copy-paste for safety now)
                    tool_outputs = []
                    tool_calls = final_run.required_action.submit_tool_outputs.tool_calls
                    for tool_call in tool_calls:
                        func_name = tool_call.function.name
                        args_str = tool_call.function.arguments
                        call_id = tool_call.id
                        if callback: callback(f"\n[System: Executing {func_name} with {args_str}...]\n")
                        try:
                            args = json.loads(args_str)
                            result = "Error: Unknown tool"
                            if func_name == "read_file": result = Tools.read_file(args.get("file_path"))
                            elif func_name == "write_file": result = Tools.write_file(args.get("file_path"), args.get("content"))
                            elif func_name == "list_directory": result = Tools.list_directory(args.get("dir_path"))
                            elif func_name == "web_search": result = Tools.web_search(args.get("query"))
                            elif func_name == "send_email": result = Tools.send_email(args.get("to_email"), args.get("subject"), args.get("body"), args.get("attachments"))
                            elif func_name == "execute_python": result = Tools.execute_python(args.get("code"))
                            tool_outputs.append({"tool_call_id": call_id, "output": str(result)})
                            if callback: callback(f"\n[System: Tool Output: {str(result)[:100]}...]\n")
                        except Exception as e:
                            tool_outputs.append({"tool_call_id": call_id, "output": f"Error: {e}"})
                    
                    with self.openai_client.beta.threads.runs.submit_tool_outputs_stream(
                        thread_id=thread.id,
                        run_id=final_run.id,
                        tool_outputs=tool_outputs,
                        event_handler=MyEventHandler(self.openai_client, thread.id, self.assistant.id),
                    ) as stream:
                        stream.until_done()
                        final_run = stream.get_final_run()

        # Retrieve the final message to return as string (for memory log)
        messages = self.openai_client.beta.threads.messages.list(thread_id=thread.id, limit=1)
        if messages.data:
            content = messages.data[0].content[0].text.value
            return content
        return ""

    def _chat_ollama(self, user_input: str, history: List[Dict[str, str]], callback: Callable[[str], None]) -> str:
        # Ollama doesn't support tools natively in the python lib the same way yet (or it varies).
        # We will do a simple chat for now.
        # Convert messages to Ollama format
        messages = [{"role": "system", "content": config.system_prompt}] + history + [{"role": "user", "content": user_input}]
        ollama_messages = []
        for m in messages:
            if m["role"] != "tool": # Skip tool outputs for now as Ollama might get confused
                ollama_messages.append({"role": m["role"], "content": m["content"]})
        
        stream = ollama.chat(
            model=config.ollama_model,
            messages=ollama_messages,
            stream=True,
        )
        
        full_response = ""
        for chunk in stream:
            content = chunk['message']['content']
            full_response += content
            if callback: callback(content)
            
        return full_response

